"""w12_chunks.py — W12D2 산출물. 함정 3종을 막도록 다시 자른 코퍼스.

build_v1(step): step1=표 행 분해 · step2=+빠진 문서 보강 · step3=+판 분리 & 문맥 요약
"""
import json, os, re, sys
sys.path.insert(0, os.path.abspath("../../00_공통"))
sys.path.insert(0, ".")
import rag_lib as R
import rag_v1 as V

PDF = os.path.join(os.path.abspath("../../assets"), "terms.pdf")

STATEMENT = ['명세서 기본정보. 회원명은 김수현이고 카드번호는 1234-56**-****-7890이다. 이용기간은 2026-08-01 ~ 2026-08-31이다. 결제일은 2026-09-25이다. 청구금액은 384,200원이다.', '명세서 이용내역 앞부분. 08-03 행복마트 강남점 일시불 58,400원. 08-07 한빛주유소 일시불 70,000원. 08-12 온라인서점 북웨이 3개월 할부 96,000원.', '명세서 이용내역 뒷부분. 08-19 우리동네 약국 일시불 12,800원. 08-23 행복카페 역삼 일시불 23,000원. 08-28 가전마트 디지털존 6개월 할부로 결제한 금액은 124,000원이다.']

TABLE = [('일반', '10,000', '15,000'), ('골드', '30,000', '40,000'), ('플래티넘', '80,000', '100,000')]

def build_v1(step=3):
    """step1 = 표 행 분해 · step2 = +빠진 문서 보강 · step3 = +판 분리 & 문맥 요약"""
    raw = {c["id"]: c["text"] for c in R.load_terms_chunks(PDF)}
    C = []
    def add(key, cid, ctx, body):
        C.append(V.chunk(key, cid, ctx if step >= 3 else "", body))

    for cid in ("제1조", "제5조", "제7조", "제15조", "제18조"):
        add(cid, cid, f"행복카드 약관 {cid}의 본문이다.", raw[cid])
    add("제12조", "제12조",
        "행복카드 약관 제12조이며 연회비를 언제 부과하고 청구하는지 정한 조항의 본문이다.", raw["제12조"])
    add("제21조", "제21조", "행복카드 약관 제21조 해지 조항의 본문이다.",
        re.split(r"\[별표1\]", raw["제21조"])[0].strip())

    # ② 표 분해 방어 — 표를 '행 한 줄 = 청크 하나'로 푼다
    for g, dom, ovs in TABLE:
        add(f"별표1-{g}-국내", "별표1", "행복카드 약관 [별표1] 카드 등급별 요금표에서 뽑은 한 행이다.",
            f"{g} 등급 카드의 국내전용 연회비는 {dom}원이다.")
        add(f"별표1-{g}-해외", "별표1", "행복카드 약관 [별표1] 카드 등급별 요금표에서 뽑은 한 행이다.",
            f"{g} 등급 카드의 해외겸용 연회비는 {ovs}원이다.")

    # 빠진 문서 보강 — 표지(판 정보) · 명세서(10주차 산출물)
    if step >= 2:
        add("표지", "표지", "행복카드 개인회원 약관의 표지이며 이 문서가 어느 판인지 알려 준다.",
            "행복카드 개인회원 약관이다. 이 약관은 2026년 3월에 개정된 판이다.")
        for i, s in enumerate(STATEMENT):
            add(f"명세서-{i}", "명세서",
                "2026년 8월 행복카드 이용대금 명세서에서 10주차에 뽑아 둔 내용이다.", s)

    # ③ 판 분리 — 두 판이 섞인 조항을 판별로 쪼갠다
    if step >= 3:
        add("제12조의2-본문", "제12조의2",
            "행복카드 약관 제12조의2 연회비 면제의 일반 기준이며 2026년 3월 이후에 발급된 회원에게 적용된다.",
            "제12조의2(연회비 면제) 직전 1년간 이용금액이 300,000원 이상인 회원은 다음 연도 연회비를 면제한다.")
        add("제12조의2-단서", "제12조의2",
            "행복카드 약관 제12조의2의 예외 규정이며 2026년 3월 이전에 발급된 회원에게만 적용되는 옛 판의 기준이다.",
            "단, 2026년 3월 이전에 발급된 회원에게는 200,000원 기준을 적용한다.")
    else:
        add("제12조의2", "제12조의2", "행복카드 약관 제12조의2의 본문이다.", raw["제12조의2"])
    return C


def load(path="chunks_v1.jsonl"):
    """저장해 둔 청크를 그대로 읽어 온다"""
    return [V.chunk(d["key"], d["id"], d["ctx"], d["body"])
            for d in (json.loads(l) for l in open(path, encoding="utf-8"))]
